var ErrExternalIDCharsetEmpty = errors.New("external id charset is empty")

func NewExternalID() (string, error) {
	chars := []rune(externalIDCharset)
	if len(chars) == 0 {
		return "", ErrExternalIDCharsetEmpty
	}
	result := make([]rune, 4)
	max := big.NewInt(int64(len(chars)))
	for i := range result {
		n, err := rand.Int(rand.Reader, max)
		if err != nil {
			return "", err
		}
		result[i] = chars[n.Int64()]
	}
	return string(result), nil
}
